export const getMultipleTexts = (count: number): string => {
  const shuffled = [...typingTexts].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length)).join(" ");
};

export const getWikipediaTextByWords = (
  minWords: number,
  selectedCategories?: TopicCategory[]
): string => {
  const safeTarget = Math.max(200, minWords);
  const filteredWiki = getParagraphPool(selectedCategories);
  const pool = [...typingTexts, ...filteredWiki];
  const chunks: string[] = [];
  let totalWords = 0;

  while (totalWords < safeTarget) {
    const paragraph = pool[Math.floor(Math.random() * pool.length)];
    chunks.push(paragraph);
    totalWords += paragraph.trim().split(/\s+/).length;
  }

  return chunks.join(" ");
};

export const getRandomWikipediaParagraph = (
  selectedCategories?: TopicCategory[]
): string => {
  const pool = getParagraphPool(selectedCategories);
  return pool[Math.floor(Math.random() * pool.length)];
};

